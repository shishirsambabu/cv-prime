import type { CoverLetterData } from '@/lib/coverLetterData';

interface RoleSpec {
  title: string;
  stack: string;
  employerContext: string;
  proof: string;
  roleDo: string;
  roleDont: string;
  sampleOpening: string;
  sampleBody: string;
  sampleClosing: string;
}

function build(s: RoleSpec): CoverLetterData {
  return {
    dos: [
      `Name the specific ${s.stack} from the job description in your opening paragraph`,
      `Quantify at least one achievement: ${s.proof}`,
      `Reference the company's actual ${s.employerContext} and why it interests you`,
      'Keep it to 3 short paragraphs and under 300 words',
      s.roleDo,
    ],
    donts: [
      'Don\'t restate your CV line by line — use the letter to add context the CV cannot',
      'Avoid generic openers like "I am writing to express my interest" — start with a result',
      'Don\'t list every skill you have — focus on the 3–5 the job description asks for',
      'Don\'t send a letter that names a different company or role',
      s.roleDont,
    ],
    keyPoints: [
      `One concrete achievement with a measurable outcome (${s.proof})`,
      `Familiarity with the employer's ${s.employerContext}`,
      'Why this company and this role specifically, not just the job title',
      'A confident, specific close that asks for a conversation',
    ],
    sampleOpening: s.sampleOpening,
    sampleBody: s.sampleBody,
    sampleClosing: s.sampleClosing,
    faqs: [
      {
        q: `Do ${s.title} applicants in India need a cover letter?`,
        a: 'It is rarely mandatory, but a short, specific cover letter helps most when the posting asks for one, when you are changing company type or city, or when you can point to a result that maps directly to the job description. For high-volume screening, make sure your CV carries the keywords and treat the letter as a differentiator.',
      },
      {
        q: `How long should a ${s.title} cover letter be?`,
        a: 'Three short paragraphs, under 300 words, on a single page. Open with a relevant result, use the middle paragraph for one or two proof points matched to the job description, and close with a specific next step.',
      },
    ],
  };
}

