import type { CoverLetterData } from '@/lib/coverLetterData';

interface RoleSpec {
  role: string;
  proof: string;
  tools: string;
  channel: string;
  opening: string;
  body: string;
  closing: string;
  extraDo: string;
  extraDont: string;
  point: string;
  faqQ: string;
  faqA: string;
}

function build(s: RoleSpec): CoverLetterData {
  return {
    dos: [
      `Open with one concrete ${s.role.toLowerCase()} result, not a generic statement of interest`,
      `Mirror the tools and terms in the job description: ${s.tools}`,
      `Quantify your ${s.proof} with a number, a timeframe and a scope`,
      s.extraDo,
      `Close with a specific next step, such as ${s.channel}`,
    ],
    donts: [
      'Don\'t repeat your CV line by line; use the letter to add context the CV cannot',
      'Don\'t open with "I am writing to apply for..." — it wastes your strongest line',
      s.extraDont,
      'Never reuse a letter that names another company or role',
      'Don\'t exceed one page or about 300 words',
    ],
    keyPoints: [
      s.point,
      `Name the company and one specific thing about its work that connects to your ${s.role.toLowerCase()} experience`,
      'Keep to three short paragraphs: result, evidence, ask',
      'Use the same name, title and contact details as your CV so the two documents match',
    ],
    sampleOpening: s.opening,
    sampleBody: s.body,
    sampleClosing: s.closing,
    faqs: [
      { q: s.faqQ, a: s.faqA },
      {
        q: `How long should a ${s.role.toLowerCase()} cover letter be?`,
        a: 'Three short paragraphs and under 300 words. Recruiters skim, so one clear result and one clear ask beat a long career summary. Replace every bracketed placeholder with your own real numbers before sending.',
      },
    ],
  };
}

